#!/usr/bin/env python3
"""Generates shinki/qml/Shinki/ShinkiStyle.qml from shinki/tokens.json, the one source of Shinki's
values (shinki/README.md, section 6). With --check it only compares and fails when the file is stale.

  color.paper        → paper            (a role: pages name it, never the hex)
  color.onRed        → textOnRed        (QML reads "on" + capital as a signal handler)
  level[i]           → levelColor(i)    levelText[i] → levelTextColor(i)
  font.book          → bookFamily
  size.listRow       → listRowSize      (px at 96 dpi, through unit(): the platform's scale)
  space.page         → pageSpace        shape.playLarge → playLargeSize
  size.japaneseRatio → japaneseRatioMin / japaneseRatioMax
  shape.grip         → gripWidth / gripHeight     shape.sheetShadow.y → sheetShadowY
  motion.sheet       → sheetDuration (ms)         opacity.scrim → scrimOpacity
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "shinki" / "tokens.json"
OUT = ROOT / "shinki" / "qml" / "Shinki"

HEADER = """pragma Singleton
import QtQuick
import org.kde.kirigami as Kirigami

// Shinki's roles, levels, fonts and sizes (shinki/README.md). Generated by tools/shinki_style.py
// from shinki/tokens.json: change the tokens, never this file.
QtObject {
    id: style

    // A size of the bible (px at 96 dpi) in the platform's units, as Kirigami scales.
    function unit(px) {
        return Math.round(px * Kirigami.Units.gridUnit / 18)
    }
"""

QMLDIR = "module Shinki\nsingleton ShinkiStyle 1.0 ShinkiStyle.qml\n"


def role(name):
    """A colour role's QML name: onRed would be a handler, it becomes textOnRed."""
    return "textOn" + name[2:] if name.startswith("on") and name[2:3].isupper() else name


def cap(name):
    return name[0].upper() + name[1:]


def scaled(value):
    return f"unit({value})"


def generate(tokens):
    lines = [HEADER]

    lines.append("    // Colours (section 2).")
    for name, value in tokens["color"].items():
        lines.append(f'    readonly property color {role(name)}: "{value}"')

    lines.append("")
    lines.append("    // Levels 0..4 (open … exam-ready) and the colour of their number on them.")
    levels = ", ".join(f'"{v}"' for v in tokens["level"])
    texts = ", ".join(f'"{tokens["color"][role]}"' for role in tokens["levelText"])
    lines.append(f"    readonly property var levels: [{levels}]")
    lines.append(f"    readonly property var levelTexts: [{texts}]")
    lines.append("    function levelColor(level) {")
    lines.append("        return levels[Math.max(0, Math.min(levels.length - 1, level))]")
    lines.append("    }")
    lines.append("    function levelTextColor(level) {")
    lines.append("        return levelTexts[Math.max(0, Math.min(levelTexts.length - 1, level))]")
    lines.append("    }")

    lines.append("")
    lines.append("    // Fonts (section 3).")
    for name, value in tokens["font"].items():
        lines.append(f'    readonly property string {name}Family: "{value}"')

    lines.append("")
    lines.append("    // Sizes (section 3), spaces and shapes (section 4).")
    for name, value in tokens["size"].items():
        if isinstance(value, list):
            lines.append(f"    readonly property real {name}Min: {value[0]}")
            lines.append(f"    readonly property real {name}Max: {value[1]}")
            continue
        lines.append(f"    readonly property int {name}Size: {scaled(value)}")
    for name, value in tokens["space"].items():
        lines.append(f"    readonly property int {name}Space: {scaled(value)}")
    for name, value in tokens["shape"].items():
        if isinstance(value, list):
            lines.append(f"    readonly property int {name}Width: {scaled(value[0])}")
            lines.append(f"    readonly property int {name}Height: {scaled(value[1])}")
        elif isinstance(value, dict):
            for sub, v in value.items():
                lines.append(f"    readonly property int {name}{cap(sub)}: {scaled(v)}")
        else:
            lines.append(f"    readonly property int {name}Size: {scaled(value)}")
    lines.append(f"    readonly property int lineWidth: Math.max(1, {scaled(tokens['line'])})")
    lines.append(f"    readonly property int selectedBarWidth: {scaled(tokens['selectedBar'])}")
    lines.append(f"    readonly property int focusWidth: {scaled(tokens['focusWidth'])}")

    lines.append("")
    lines.append("    // Motion (ms) and opacities (section 4).")
    for name, value in tokens["motion"].items():
        lines.append(f"    readonly property int {name}Duration: {value}")
    for name, value in tokens["opacity"].items():
        lines.append(f"    readonly property real {name}Opacity: {value}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    files = {OUT / "ShinkiStyle.qml": generate(tokens), OUT / "qmldir": QMLDIR}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("shinki_style: stale, run tools/shinki_style.py:", *stale)
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
